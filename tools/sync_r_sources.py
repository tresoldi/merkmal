#!/usr/bin/env python3
"""Copy the C core into the R package, so that r/ builds on its own.

An R source package must contain everything it compiles: `R CMD build` and
`R CMD INSTALL` see only the package directory, and an install from GitHub
(`remotes::install_github("tresoldi/merkmal", subdir = "r")`) has nothing
else. The C core is therefore copied into `r/src/merkmal/`, with the files
that go with it, and the copies are committed, as other generated files are
(docs/development/adr/0003-generated-artifacts-are-committed.md). This script
is the only way they change.

Copied:

    include/merkmal.h          -> r/src/merkmal/include/merkmal.h
    src/*.c, src/*.h           -> r/src/merkmal/
    src/generated/*.c, *.h     -> r/src/merkmal/generated/  (the full data profile)
    NOTICE                     -> r/inst/NOTICE
    tests/golden/<system>_distances.tsv and the categorical
    <system>_features.tsv      -> r/tests/testthat/golden/

and `r/src/Makevars` is written with the list of object files, since a
portable Makevars cannot glob.

    tools/sync_r_sources.py           # copy
    tools/sync_r_sources.py --check   # fail if any copy is out of date (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "r"
CORE = R / "src" / "merkmal"
SYSTEMS = ["descriptive", "distinctive", "phoible", "pbase-hc", "pbase-jfh", "pbase-spe", "pbase-uftc"]
CATEGORICAL = ["descriptive", "distinctive"]
GLUE = ["init.c", "merkmal_r.c", "sha256.c"]  # the R package's own sources, in r/src/


def wanted() -> dict[Path, bytes]:
    out: dict[Path, bytes] = {}
    out[CORE / "include" / "merkmal.h"] = (ROOT / "include" / "merkmal.h").read_bytes()
    for path in sorted((ROOT / "src").glob("*.[ch]")):
        out[CORE / path.name] = path.read_bytes()
    for path in sorted((ROOT / "src" / "generated").glob("*.[ch]")):
        out[CORE / "generated" / path.name] = path.read_bytes()
    out[R / "inst" / "NOTICE"] = (ROOT / "NOTICE").read_bytes()
    golden = ROOT / "tests" / "golden"
    for system in SYSTEMS:
        name = f"{system}_distances.tsv"
        out[R / "tests" / "testthat" / "golden" / name] = (golden / name).read_bytes()
    for system in CATEGORICAL:
        name = f"{system}_features.tsv"
        out[R / "tests" / "testthat" / "golden" / name] = (golden / name).read_bytes()
    out[R / "src" / "Makevars"] = makevars(out)
    return out


def makevars(files: dict[Path, bytes]) -> bytes:
    core = sorted(p.relative_to(R / "src") for p in files if p.suffix == ".c" and CORE in p.parents)
    objects = [name.replace(".c", ".o") for name in GLUE] + [str(p.with_suffix(".o")) for p in core]
    lines = [
        "# Generated by tools/sync_r_sources.py; do not edit.",
        "PKG_CPPFLAGS = -Imerkmal/include -Imerkmal",
        "OBJECTS = \\",
    ]
    lines += [f"\t{obj} \\" for obj in objects[:-1]] + [f"\t{objects[-1]}", ""]
    return "\n".join(lines).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a copy is out of date")
    args = parser.parse_args()

    files = wanted()
    stale = [p for p, data in files.items() if not p.exists() or p.read_bytes() != data]
    managed = {CORE, R / "tests" / "testthat" / "golden"}
    # Build products (.o, .so) are not sources; git ignores them.
    extra = [
        p for d in managed if d.exists() for p in d.rglob("*")
        if p.is_file() and p.suffix in {".c", ".h", ".tsv"} and p not in files
    ]
    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        for path in extra:
            print(f"not in the C core: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale or extra:
            print("run tools/sync_r_sources.py", file=sys.stderr)
            return 1
        print("the R package's copy of the C core is up to date")
        return 0
    for path in extra:
        path.unlink()
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(files[path])
    print(f"updated {len(stale)} files, removed {len(extra)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
