"""Generate the Unicode normalization tables compiled into the C library.

merkmal used libutf8proc for its final NFC and NFD passes when it was
installed and an IPA-focused approximation when it was not, so one commit gave
different strings on different machines: a fallback build returned `ỹ`
decomposed where a utf8proc build composed it, and two utf8proc builds could
still disagree when their utf8proc versions carried different Unicode versions.
These tables make normalization a property of the source tree. Every build --
CMake, the Python extension, WebAssembly -- runs the same NFC and NFD, at the
Unicode version recorded in the output.

The tables come from Python's `unicodedata`, so the Unicode version is the one
the generating interpreter carries. `scripts/check_generated_data.py` compares
the committed file only under an interpreter with that same version.

Three tables, all sorted by code point for binary search:

- canonical combining classes, nonzero entries only;
- full canonical decompositions, already applied recursively, excluding
  Hangul syllables, which are decomposed algorithmically;
- primary composites: the canonical pairs NFC recomposes, which leaves out
  singletons, non-starter decompositions and the composition exclusions.
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "src" / "generated" / "unicode_data.c"
MAX_CODE_POINT = 0x10FFFF
HANGUL_FIRST = 0xAC00
HANGUL_LAST = 0xD7A3


def is_surrogate(code_point: int) -> bool:
    return 0xD800 <= code_point <= 0xDFFF


def canonical_mapping(code_point: int) -> list[int] | None:
    """The one-level canonical decomposition, or None."""
    raw = unicodedata.decomposition(chr(code_point))
    if not raw or raw.startswith("<"):
        return None
    return [int(part, 16) for part in raw.split()]


def combining_classes() -> list[tuple[int, int]]:
    return [
        (cp, unicodedata.combining(chr(cp)))
        for cp in range(MAX_CODE_POINT + 1)
        if not is_surrogate(cp) and unicodedata.combining(chr(cp))
    ]


def decompositions() -> list[tuple[int, list[int]]]:
    out = []
    for cp in range(MAX_CODE_POINT + 1):
        if is_surrogate(cp) or HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        if canonical_mapping(cp) is None:
            continue
        full = [ord(c) for c in unicodedata.normalize("NFD", chr(cp))]
        out.append((cp, full))
    return out


def compositions() -> list[tuple[int, int, int]]:
    out = []
    for cp in range(MAX_CODE_POINT + 1):
        if is_surrogate(cp) or HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        mapping = canonical_mapping(cp)
        if mapping is None or len(mapping) != 2:
            continue
        # A pair NFC actually rebuilds. This is what excludes the composition
        # exclusions and the non-starter decompositions without listing them.
        if unicodedata.normalize("NFC", chr(mapping[0]) + chr(mapping[1])) != chr(cp):
            continue
        out.append((mapping[0], mapping[1], cp))
    out.sort()
    return out


def emit_array(name: str, ctype: str, values: list[int], per_line: int = 10) -> list[str]:
    lines = [f"static const {ctype} {name}[] = {{"]
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("    " + ", ".join(f"0x{value:X}" for value in chunk) + ",")
    lines.append("};")
    lines.append("")
    return lines


def generate() -> str:
    ccc = combining_classes()
    decomp = decompositions()
    comp = compositions()

    pool: list[int] = []
    offsets: list[int] = []
    lengths: list[int] = []
    for _, full in decomp:
        offsets.append(len(pool))
        lengths.append(len(full))
        pool.extend(full)
    if len(pool) > 0xFFFF or max(lengths) > 0xFF:
        raise SystemExit("decomposition pool outgrew its index types")

    lines = [
        '#include "unicode_data.h"',
        "",
        "/* This file is generated by tools/generate_unicode_data.py from the",
        f" * Unicode Character Database {unicodedata.unidata_version}. Do not edit. */",
        "",
        f'const char *const mki_unicode_version = "{unicodedata.unidata_version}";',
        "",
    ]
    lines += emit_array("mk_ccc_code_points", "unsigned int", [cp for cp, _ in ccc])
    lines += emit_array("mk_ccc_classes", "unsigned char", [value for _, value in ccc], 16)
    lines += emit_array("mk_decomposition_code_points", "unsigned int", [cp for cp, _ in decomp])
    lines += emit_array("mk_decomposition_offsets", "unsigned short", offsets, 12)
    lines += emit_array("mk_decomposition_lengths", "unsigned char", lengths, 16)
    lines += emit_array("mk_decomposition_pool", "unsigned int", pool)
    lines += emit_array("mk_composition_first", "unsigned int", [a for a, _, _ in comp])
    lines += emit_array("mk_composition_second", "unsigned int", [b for _, b, _ in comp])
    lines += emit_array("mk_composition_result", "unsigned int", [c for _, _, c in comp])
    lines += [
        "const mk_unicode_tables mki_unicode_tables = {",
        "    mk_ccc_code_points,",
        "    mk_ccc_classes,",
        f"    {len(ccc)},",
        "    mk_decomposition_code_points,",
        "    mk_decomposition_offsets,",
        "    mk_decomposition_lengths,",
        "    mk_decomposition_pool,",
        f"    {len(decomp)},",
        "    mk_composition_first,",
        "    mk_composition_second,",
        "    mk_composition_result,",
        f"    {len(comp)}",
        "};",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.output.write_text(generate(), encoding="utf-8")
    print(
        f"wrote {args.output} (Unicode {unicodedata.unidata_version})",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
